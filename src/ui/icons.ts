/** Accepts Lucide's PascalCase, kebab-case or a plain lowercase word. */
export function resolveIcon(name: string): LucideIcon | undefined {
  const kebab = name
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/[\s_]+/g, "-")
    .toLowerCase();
  return icons[kebab] ?? icons[name.toLowerCase()];
}
